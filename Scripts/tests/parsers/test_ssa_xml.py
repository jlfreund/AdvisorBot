#!/usr/bin/env python3
"""
Social Security statement XML parsing.

Two concerns: the earnings record is read correctly from the schema the SSA actually
publishes, and a hostile XML document cannot turn the parser into an amplification bomb
or a file-read primitive (findings SA-13, SA-18).

Fixture XML is generated by the portfolio generator from a named earnings profile, so the
expected year/amount table is derivable rather than pasted.
"""

from __future__ import annotations

import pytest

from ingest.framework import IngestContext
from ingest.plugins.ssa_xml import SsaXmlStatementPlugin
from ingest.ssa_xml import parse_ssa_xml_path, parse_ssa_xml_text
from tests.generate import builder, spec as spec_mod
from tests.support import roots

SLUG = "p3_retiree_annuities"


def _fixture_xml_paths() -> list:
    return sorted((roots.PORTFOLIOS_DIR / SLUG / "Statements" / "ssa").glob("*.xml"))


@pytest.mark.feature("social_security")
def test_generated_ssa_xml__parses_with_the_expected_earnings_table():
    """
    The fixture's XML round-trips to the earnings table its spec profile describes.

    Exercises: a two-investor household whose Social Security history comes from XML
    rather than from summary fields, which is the path `external_file` takes.
    """
    spec = spec_mod.load(roots.spec_path(SLUG))
    investors = {str(inv["id"]): inv for inv in spec["investors"]}
    paths = _fixture_xml_paths()
    assert len(paths) == len([i for i in investors.values() if (i.get("ssa") or {}).get("emit_xml")])

    for path in paths:
        investor_id = path.name.split("_ssa_statement")[0]
        expected = builder.earnings_table(investors[investor_id]["ssa"])
        result = parse_ssa_xml_text(path.read_text(encoding="utf-8"), file_name=path.name)
        assert result.get("ok"), result.get("error")
        earnings = {str(k): float(v) for k, v in (result.get("annual_earnings") or {}).items()}
        # Zero-earning years are omitted by the parser: a gap year is an absent row, not a
        # reported zero, which is how the SSA statement itself reads.
        earned = {year: amount for year, amount in expected.items() if amount}
        assert set(earnings) == set(earned), f"{path.name}: earnings years differ"
        for year, amount in earned.items():
            assert earnings[year] == pytest.approx(float(amount))


@pytest.mark.feature("social_security")
def test_ssa_plugin__detects_and_summarises_the_statement():
    """The plugin claims an SSA document and reports its span as an account row."""
    path = _fixture_xml_paths()[0]
    ctx = IngestContext(file_path=path, rel_path=path.name, cfg={})
    plugin = SsaXmlStatementPlugin()
    assert plugin.detect(ctx) == 1.0
    stmt = plugin.parse(ctx)
    assert stmt.doc_type == "SSA_XML"
    assert stmt.account_id == "SSA"
    assert stmt.account_type == "SSN"
    assert stmt.positions == []


@pytest.mark.feature("social_security")
@pytest.mark.regression("SA-18")
def test_entity_declaration__does_not_expand_recursively():
    """
    An XML document declaring internal entities is handled without amplification.

    Exercises: the adversarial fixture ships a document with nested entity definitions.
    Either the parser rejects it or it returns the literal text, but it must not expand
    exponentially and must not hang.
    """
    path = roots.PORTFOLIOS_DIR / "p5_adversarial" / "Malformed" / "entity_bomb.xml"
    content = path.read_text(encoding="utf-8")
    result = parse_ssa_xml_text(content, file_name=path.name)
    if result.get("ok"):
        name = str(result.get("name") or "")
        assert len(name) < 1000, "entity expansion produced an implausibly long value"
    else:
        assert result.get("error"), "a rejection must explain itself"


@pytest.mark.feature("social_security")
def test_parse_ssa_xml_text__non_xml_input__reports_an_error_rather_than_raising():
    """Garbage in gives a structured error, which is what the audit table renders."""
    result = parse_ssa_xml_text("this is not xml at all", file_name="junk.xml")
    assert not result.get("ok")
    assert "Invalid XML" in str(result.get("error")) or result.get("error")


@pytest.mark.portfolio("p3_retiree_annuities")
@pytest.mark.feature("social_security")
@pytest.mark.regression("SA-13")
def test_parse_ssa_xml_path__outside_the_portfolio__is_refused(root, tmp_path):
    """
    An absolute path outside the active portfolio is refused, not read.

    Exercises: the confinement added for SA-13. Without it this entry point is an
    arbitrary-file read for anything that can reach the authenticated API.
    """
    outside = tmp_path / "elsewhere.xml"
    outside.write_text("<x/>", encoding="utf-8")
    result = parse_ssa_xml_path(str(outside))
    assert not result.get("ok")
    assert "within the active portfolio" in str(result.get("error")).lower()


@pytest.mark.portfolio("p3_retiree_annuities")
@pytest.mark.feature("social_security")
def test_parse_ssa_xml_path__missing_file_inside_the_portfolio__reports_not_found(root):
    """A path that is allowed but absent is reported as missing."""
    result = parse_ssa_xml_path("Statements/ssa/does_not_exist.xml")
    assert not result.get("ok")
    assert "not found" in str(result.get("error")).lower()


